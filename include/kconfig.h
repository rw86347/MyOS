#ifndef KCONFIG_H
#define KCONFIG_H

#include <stdint.h>

/*
 * The kernel config (docs/KERNEL-CONFIG.md): the mode, which task owns
 * which of the 20 slots, the power savings, and for each task the program
 * that may take its slots. Settings › Kernel saves it to a myos-config
 * partition; the build links in a default made from config/slots.conf.
 *
 * Between the two "generated" lines: exactly what
 * `tools/kconfig/kconfig.py header` prints (the build compares them), so
 * these structs are the same bytes the Python and Settings write.
 */

/* --- generated by tools/kconfig/kconfig.py header: do not edit --- */
/* Generated by tools/kconfig/kconfig.py header: the kernel config
   (docs/KERNEL-CONFIG.md). Every field sits at a naturally aligned
   offset: no packing needed. */
#define KCFG_MAGIC        "MYOSKCFG"
#define KCFG_TASK_MAGIC   "MYOSTASK"
#define KCFG_VERSION      1
#define KCFG_SLOTS        20
#define KCFG_MAX_TASKS    18
#define KCFG_OWNER_FREE   0x00
#define KCFG_OWNER_OS     0xFF
#define KCFG_RT_LEFTOVER  (1u << 0)
#define KCFG_RT_DEFER_IRQ (1u << 1)
#define KCFG_TASK_START_AT_BOOT (1u << 0)
#define KCFG_TASK_RESTART       (1u << 1)
#define KCFG_BOOT_SECTOR_A  0   /* in the myos-config partition */
#define KCFG_BOOT_SECTOR_B  1
#define KCFG_TASKS_SECTOR_A 16
#define KCFG_TASKS_SECTOR_B 32

#define KCFG_PM_CPU_SPEED        (1u <<  0)  /* Change processor speed */
#define KCFG_PM_NO_BOOST         (1u <<  1)  /* Turn off boost */
#define KCFG_PM_DEEP_IDLE        (1u <<  2)  /* Deep idle states */
#define KCFG_PM_C1E              (1u <<  3)  /* Enhanced halt (C1E) */
#define KCFG_PM_THROTTLE         (1u <<  4)  /* Clock modulation */
#define KCFG_PM_TICKLESS         (1u <<  5)  /* Skip unneeded timer ticks */
#define KCFG_PM_SMT_OFF          (1u <<  6)  /* Turn off second threads */
#define KCFG_PM_CORE_PARK        (1u <<  7)  /* Park idle cores */
#define KCFG_PM_DISK_SPINDOWN    (1u <<  8)  /* Spin down hard disks */
#define KCFG_PM_SATA_LPM         (1u <<  9)  /* SATA link power management */
#define KCFG_PM_NVME_APST        (1u << 10)  /* NVMe power states */
#define KCFG_PM_PCIE_ASPM        (1u << 11)  /* PCIe link power management */
#define KCFG_PM_USB_AUTOSUSPEND  (1u << 12)  /* Suspend idle USB devices */
#define KCFG_PM_WIFI_PS          (1u << 13)  /* Wi-Fi power save */
#define KCFG_PM_AUDIO_PM         (1u << 14)  /* Power down the sound chip */
#define KCFG_PM_NIC_IDLE         (1u << 15)  /* Idle unplugged Ethernet */
#define KCFG_PM_GPU_PM           (1u << 16)  /* Graphics power management */

struct kconfig {
    char magic[8];                          /* 0x000 "MYOSKCFG" */
    uint8_t byte_order;                     /* 0x008 1 = little-endian, 2 = big-endian */
    uint8_t version;                        /* 0x009 1 */
    uint8_t arch;                           /* 0x00A 1 i386, 2 x86_64, 3 arm, 4 arm64 */
    uint8_t mode;                           /* 0x00B 0 realtime, 1 soft realtime, 2 power saving */
    uint16_t size;                          /* 0x00C 512 */
    uint16_t slot_us;                       /* 0x00E length of one slot: 1000 us */
    uint32_t generation;                    /* 0x010 +1 on every save; the task table has the same */
    uint32_t crc32;                         /* 0x014 CRC-32 (IEEE) of the block with this field 0 */
    uint8_t nslots;                         /* 0x018 20 */
    uint8_t ntasks;                         /* 0x019 names used in task_name[] */
    uint8_t os_slot[2];                     /* 0x01A {0, 10}: the system's slots */
    uint32_t rt_flags;                      /* 0x01C KCFG_RT_LEFTOVER | KCFG_RT_DEFER_IRQ */
    uint8_t slot_owner[KCFG_SLOTS];         /* 0x020 0 free, 1..18 task_name[n-1], 0xFF the OS */
    uint16_t latency_budget_us;             /* 0x034 soft realtime: slowest wake-up allowed */
    uint8_t reserved0[10];                  /* 0x036 0 */
    char task_name[KCFG_MAX_TASKS][16];     /* 0x040 18 names of 16 bytes, NUL-padded */
    uint32_t power_on;                      /* 0x160 power saving: the features switched on */
    uint32_t power_seen;                    /* 0x164 the features this machine had at the save */
    uint8_t cpu_min_pct;                    /* 0x168 slowest speed, % of the highest non-boost */
    uint8_t cpu_max_pct;                    /* 0x169 fastest speed, same scale */
    uint8_t epp;                            /* 0x16A energy preference: 0 speed .. 255 energy */
    uint8_t cstate_max;                     /* 0x16B deepest idle state: 1 = C1 ... 10 = C10 */
    uint16_t spindown_min;                  /* 0x16C idle minutes before a disk stops (0 never) */
    uint8_t reserved1[2];                   /* 0x16E 0 */
    uint8_t reserved2[144];                 /* 0x170 0: room for later versions */
};
_Static_assert(sizeof(struct kconfig) == 512, "one sector");

struct kconfig_task {
    char name[16];                          /* 0x000 the task, as in the boot block */
    char program[128];                      /* 0x010 absolute path, NUL-terminated */
    char args[96];                          /* 0x090 each NUL-terminated, then an empty one */
    uint32_t uid;                           /* 0x0F0 runs as this user ... */
    uint32_t gid;                           /* 0x0F4 ... and group */
    uint16_t flags;                         /* 0x0F8 KCFG_TASK_START_AT_BOOT | KCFG_TASK_RESTART */
    uint16_t restart_ms;                    /* 0x0FA wait before a restart */
    uint8_t reserved[4];                    /* 0x0FC 0 */
};
_Static_assert(sizeof(struct kconfig_task) == 256, "one entry");

struct kconfig_tasks {
    char magic[8];                          /* 0x000 "MYOSTASK" */
    uint8_t byte_order;                     /* 0x008 the boot block's */
    uint8_t version;                        /* 0x009 1 */
    uint8_t ntasks;                         /* 0x00A the boot block's */
    uint8_t reserved0;                      /* 0x00B 0 */
    uint32_t size;                          /* 0x00C 5120 */
    uint32_t generation;                    /* 0x010 the boot block's */
    uint32_t crc32;                         /* 0x014 CRC-32 of the 5120 bytes with this field 0 */
    uint16_t entry_size;                    /* 0x018 256 */
    uint8_t reserved1[38];                  /* 0x01A 0 */
    struct kconfig_task task[KCFG_MAX_TASKS];                /* 0x040 */
    uint8_t reserved2[448];                                /* 0x1240 */
};
_Static_assert(sizeof(struct kconfig_tasks) == 5120, "ten sectors");
/* --- end of generated --- */

#define KCFG_ARCH_I386      1
#define KCFG_ARCH_X86_64    2
#define KCFG_ARCH_ARM64     4
#define KCFG_REALTIME       0
#define KCFG_SOFT_REALTIME  1
#define KCFG_POWER_SAVING   2
#define KCFG_PARTITION_SECTORS 42       /* boot blocks, then both task lists */

struct blockdev;

/* The built-in default, then (storage_init, once the root disk is known)
   the myos-config partition of `disk`; disk NULL: the first disk with a
   good one (MyOS running from RAM, with no root disk). Logs what it used. */
void kconfig_init(void);
void kconfig_from_disk(const struct blockdev *disk);

/* The config in use. */
const struct kconfig *kconfig_boot(void);
const struct kconfig_tasks *kconfig_tasks(void);
/* Who owns slot s (0..19): "main" for the OS slots, a task's name, or
   NULL for a free slot. */
const char *kconfig_slot_owner(int s);

/* The checks (kernel/kconfig.c), also for the self-tests: NULL if the part
   is good, else what's wrong with it. */
const char *kconfig_check_boot(const struct kconfig *b);
const char *kconfig_check_tasks(const struct kconfig_tasks *t, const struct kconfig *b);
/* Is generation a newer than b (serial-number arithmetic: it may wrap)? */
int kconfig_newer(uint32_t a, uint32_t b);
/* CRC-32 (IEEE) of n bytes with the 4-byte field at `at` taken as zero. */
uint32_t kconfig_crc(const void *p, uint32_t n, uint32_t at);
/* A partition's first KCFG_PARTITION_SECTORS sectors -> the copy to use:
   'A', 'B', or 0 for none; *boot and *tasks point into image. why[0..1]
   say what was wrong with A and B (NULL: nothing). */
int kconfig_pick(const uint8_t *image, const struct kconfig **boot,
                 const struct kconfig_tasks **tasks, const char *why[2]);

#endif
